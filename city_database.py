def resolve_city_label(label: str):
    if label in CITY_BY_LABEL:
        return CITY_BY_LABEL[label]
    alias = LABEL_ALIASES.get(label)
    if alias and alias in CITY_BY_LABEL:
        return CITY_BY_LABEL[alias]
    if alias:
        for entry in CITY_BY_LABEL.values():
            if entry["name"] == alias:
                return entry
    return None
